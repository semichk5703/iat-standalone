#!/bin/sh
# provenance.sh — tie every vendored file to a pinned upstream commit.
#   ./provenance.sh verify    check third_party/ and media/minno/ byte-for-byte against upstream/ submodules
#   ./provenance.sh sync      (re)copy them from the submodules
#   ./provenance.sh manifest  print PROVENANCE.txt content: submodule commits + sha256 of every vendored file
# Needs the submodules checked out:  git submodule update --init
set -e
cd "$(dirname "$0")"
pairs() {  # vendored-path  upstream-path
    echo "third_party/stb_image.h upstream/stb/stb_image.h"
    echo "third_party/font8x8_basic.h upstream/font8x8/font8x8_basic.h"
    echo "media/minno/LICENSE-minno-tasks-Apache-2.0 upstream/minno-tasks/LICENSE"
    for f in media/minno/*.jpg; do echo "$f upstream/minno-tasks/docs/images/$(basename "$f")"; done
}
case "$1" in
  sync)    pairs | while read v u; do cp "$u" "$v"; done; echo synced ;;
  verify)  bad=0; pairs | while read v u; do cmp -s "$v" "$u" || { echo "MISMATCH $v"; bad=1; }; done
           pairs | wc -l | xargs printf '%s vendored files checked\n'; exit $bad ;;
  manifest)
    echo "# Generated by ./provenance.sh manifest — do not edit."
    echo "# Upstream repositories (git submodules under upstream/), pinned commits:"
    git submodule status | sed 's/^[ +-]/  /'
    echo "# sha256 of every vendored file, and the upstream path it is a byte-for-byte copy of:"
    pairs | while read v u; do printf '%s  %s  <- %s\n' "$(sha256sum "$v" | cut -c1-64)" "$v" "$u"; done ;;
  *) sed -n 2,6p "$0"; exit 1 ;;
esac
