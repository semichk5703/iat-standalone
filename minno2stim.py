#!/usr/bin/env python3
"""Convert a minno-tasks IAT config (github.com/baranan/minno-tasks, IAT/qualtrics/*.js)
into stimuli.txt for ./iat.   Usage: minno2stim.py exampleQIATgendercareer.js > gendercareer.txt
Image stimuli become paths under media/minno/ (copy them from minno-tasks/docs/images/)."""
import re, sys
IMGDIR = '../media/minno/'   # where minno-tasks/docs/images/*.jpg live, relative to stimuli/

src = open(sys.argv[1], encoding='utf-8', errors='replace').read()
src = re.sub(r'//[^\n]*', '', src)                       # comments hold decoy 'word:' text
src = re.sub(r'/\*.*?\*/', '', src, flags=re.S)

def braced(text, start):
    """Return the text of the {...} or [...] that opens at/after `start` (brace-matched)."""
    i = text.index('{', start) if text.find('{', start) != -1 and (text.find('[', start) == -1 or text.find('{', start) < text.find('[', start)) else text.index('[', start)
    opener, closer = text[i], {'{': '}', '[': ']'}[text[i]]
    depth = 0
    for j in range(i, len(text)):
        if text[j] == opener: depth += 1
        elif text[j] == closer:
            depth -= 1
            if depth == 0: return text[i:j + 1]
    raise ValueError('unbalanced')

def key_block(text, key):
    m = re.search(r'\b' + key + r'\s*:', text)
    if not m: sys.exit(f'{key} not found')
    return braced(text, m.end())

def media_list(body):
    m = re.search(r'stimulusMedia\s*:\s*', body)
    rest = body[m.end():]
    if rest.lstrip().startswith('['):
        return braced(rest, 0)
    var = re.match(r'\s*(\w+)', rest).group(1)                 # stimulusMedia : darkMedia
    vm = re.search(r'\b' + var + r'\s*=\s*', src)
    if not vm: sys.exit(f'cannot resolve stimulusMedia variable {var}')
    return braced(src, vm.end())

out = {}
for key, name in (('category1', 'target_a'), ('category2', 'target_b'),
                  ('attribute1', 'attr_a'), ('attribute2', 'attr_b')):
    body = key_block(src, key)
    title = re.search(r"name\s*:\s*'([^']*)'", body).group(1)
    media = media_list(body)
    words  = re.findall(r"\{\s*word\s*:\s*'([^']*)'\s*\}", media)
    images = re.findall(r"\{\s*image\s*:\s*'([^']*)'", media)
    for var, idx in re.findall(r"\{\s*word\s*:\s*([A-Za-z_]\w*)\[(\d+)\]", media):   # {word: negWords[0]}
        vm = re.search(r'\b' + var + r"\s*=\s*(?:API\.shuffle\()?\s*\[", src)
        if not vm: sys.exit(f'{key} ({title}): cannot resolve {var}')
        arr = re.findall(r"'([^']*)'", braced(src, vm.end() - 1))
        words.append(arr[int(idx)])
    refs = []
    words += [IMGDIR + im for im in images]        # image items: path relative to the stimuli file
    if refs and not words:
        sys.exit(f'{key} ({title}) builds its words in code — transcribe them by hand')
    if not words:
        sys.exit(f'{key} ({title}) has no word stimuli')
    out[name] = (title, [w.strip() for w in words])

import subprocess, os
src_dir = os.path.dirname(os.path.abspath(sys.argv[1]))
try:
    commit = subprocess.run(['git', '-C', src_dir, 'rev-parse', 'HEAD'], capture_output=True, text=True, check=True).stdout.strip()
    rel = subprocess.run(['git', '-C', src_dir, 'ls-files', '--full-name', os.path.abspath(sys.argv[1])], capture_output=True, text=True).stdout.strip()
except Exception:
    commit, rel = 'unknown', sys.argv[1]
print(f'# Source: github.com/baranan/minno-tasks {rel} @ {commit[:12]}  (Apache-2.0; Project Implicit task library)')
print(f'# Generated by minno2stim.py; images are byte copies of docs/images/ at that commit (see PROVENANCE.txt).')
for k, (t, ws) in out.items():
    print(f'{k}: {t}')
    print(f'{k}_items: {", ".join(ws)}')
