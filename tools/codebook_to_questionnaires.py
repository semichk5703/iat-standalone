#!/usr/bin/env python3
"""Turn Project Implicit's public Race IAT codebook into the questionnaire data the offline race study runs.

    python3 tools/codebook_to_questionnaires.py [CODEBOOK.csv] [OUTPUT.js]
        CODEBOOK  default references/race-iat-dataset/Race_IAT.public.2025.codebook.csv
        OUTPUT    default offline/studies/race/codebook_items.js

The codebook lists every variable the live Race IAT records, with its question wording ("Label") and its
answer options with their recorded codes ("Values", e.g. "Strongly Disagree=1; ...").  A scale here is
every questionnaire item sharing a variable-name prefix (sdof1..sdof16 -> scale "sdof"); the output keeps
the codebook's wording and codes exactly, so a result row can be read against the codebook directly.

Which variables are scale items is decided by the rule in CodebookScales.is_scale_item, and nothing else:
there is no hand-kept list to drift out of date when a new codebook is used."""
import argparse
import csv
import hashlib
import json
import os
import re
import sys

REPOSITORY = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_CODEBOOK = os.path.join(REPOSITORY, 'references/race-iat-dataset/Race_IAT.public.2025.codebook.csv')
DEFAULT_OUTPUT = os.path.join(REPOSITORY, 'offline/studies/race/codebook_items.js')


class CodebookScales:
    """The scales in one codebook: {prefix: [item, ...]}, items in their numbered order."""

    # A variable's scale is its name without the item number: 'sdof12' -> 'sdof', 'gsrace14a' -> 'gsrace'.
    ITEM_NUMBER = re.compile(r'^(?P<prefix>[A-Za-z]+)(?P<number>\d+)(?P<part>[a-z]?)$')
    # Variables that are numbered but are not questionnaire items: the IAT's own statistics per block.
    NOT_QUESTIONNAIRES = ('Mn_', 'SD_', 'N_', 'pct_', 'PCT_', 'D_')

    def __init__(self, codebook_path):
        self.codebook_path = codebook_path
        with open(codebook_path, encoding='utf-8-sig') as source:
            self.rows = list(csv.DictReader(source))
        self.scales = {}
        for row in self.rows:
            if self.is_scale_item(row):
                match = self.ITEM_NUMBER.match(row['Variable Names'])
                self.scales.setdefault(match['prefix'], []).append(row)
        # a scale needs at least two items; a lone numbered variable is a demographic (e.g. edu_14)
        self.scales = {prefix: items for prefix, items in self.scales.items() if len(items) >= 2}
        for items in self.scales.values():
            items.sort(key=self.item_order)

    def is_scale_item(self, row):
        """A numbered variable with coded answer options, not one of the IAT's statistics."""
        name = row['Variable Names']
        return (self.ITEM_NUMBER.match(name) is not None
                and not name.startswith(self.NOT_QUESTIONNAIRES)
                and '=' in row['Values'])

    def item_order(self, row):
        match = self.ITEM_NUMBER.match(row['Variable Names'])
        return int(match['number']), match['part']

    @staticmethod
    def answers(values):
        """'Strongly Disagree=1; Disagree=2' -> [{'text': 'Strongly Disagree', 'value': 1}, ...]."""
        answers = []
        for option in values.split(';'):
            text, _, code = option.strip().rpartition('=')
            answers.append({'text': text.strip(), 'value': int(code) if code.strip().isdigit() else code.strip()})
        return answers

    def as_data(self):
        return {prefix: [{'name': row['Variable Names'], 'stem': row['Label'], 'answers': self.answers(row['Values'])}
                         for row in items]
                for prefix, items in sorted(self.scales.items())}

    def source_digest(self):
        with open(self.codebook_path, 'rb') as source:
            return hashlib.sha256(source.read()).hexdigest()


class QuestionnaireModuleWriter:
    """Writes the scales as a RequireJS module, so the study loads them like any other script."""

    def __init__(self, scales):
        self.scales = scales

    def text(self):
        source = os.path.relpath(self.scales.codebook_path, REPOSITORY).replace(os.sep, '/')
        # one item per line: a codebook change shows up in a diff as the changed items only
        scales = [f'    {json.dumps(prefix)}: [\n' + ',\n'.join('        ' + json.dumps(item, ensure_ascii=False) for item in items) + '\n    ]'
                  for prefix, items in self.scales.as_data().items()]
        data = '{\n' + ',\n'.join(scales) + '\n    }'
        return (f'// Generated by tools/codebook_to_questionnaires.py from {source}\n'
                f'// (sha256 {self.scales.source_digest()}).  Do not edit: change the tool or the codebook and rerun it.\n'
                '// Each scale: the codebook variables sharing a name prefix, with their wording and answer codes verbatim.\n'
                f'define([], function () {{\n    return {data};\n}});\n')

    def write(self, path):
        os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
        with open(path, 'w', encoding='utf-8', newline='\n') as out:
            out.write(self.text())


class CodebookApp:
    def run(self, argv):
        parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
        parser.add_argument('codebook', nargs='?', default=DEFAULT_CODEBOOK)
        parser.add_argument('output', nargs='?', default=DEFAULT_OUTPUT)
        args = parser.parse_args(argv)
        scales = CodebookScales(args.codebook)
        QuestionnaireModuleWriter(scales).write(args.output)
        item_count = sum(len(items) for items in scales.scales.values())
        print(f'wrote {args.output}: {len(scales.scales)} scales, {item_count} items: {" ".join(sorted(scales.scales))}')
        return 0


if __name__ == '__main__':
    sys.exit(CodebookApp().run(sys.argv[1:]))
